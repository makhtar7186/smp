# Jours de la semaine (indexés comme strftime('%w') : 0 = dimanche)
JOURS_SEMAINE: dict[str, list[str]] = {
    "fr": ["Dim", "Lun", "Mar", "Mer", "Jeu", "Ven", "Sam"],
    "en": ["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
    "zh": ["周日", "周一", "周二", "周三", "周四", "周五", "周六"],
}


def jours_semaine() -> list[str]:
    """Libellés des jours dans la langue active (index 0 = dimanche)."""
    return JOURS_SEMAINE.get(_langue_active, JOURS_SEMAINE["fr"])

_langue_active: str = config.lire_langue()

NOMS_LANGUES: dict[str, str] = {"fr": "Français", "en": "English", "zh": "中文"}


def langue_active() -> str:
    """Retourne le code de la langue active."""
    return _langue_active


def definir_langue(langue: str) -> None:
    """Change la langue active et la persiste dans app/data/settings.json
    (application principale)."""
    global _langue_active
    if langue in _TRADUCTIONS:
        _langue_active = langue
        config.sauver_langue(langue)


def definir_langue_memoire(langue: str) -> None:
    """Change la langue active en mémoire seulement, sans passer par
    `app.config`/`settings.json` — utilisé par le mode client (`app/client/`),
    qui n'a pas de base SQLite locale et persiste son propre choix de langue
    dans `client_config.json` plutôt que dans les réglages de l'application
    principale."""
    global _langue_active
    if langue in _TRADUCTIONS:
        _langue_active = langue


def t(cle: str) -> str:
    """Traduit une clé dans la langue active (repli sur le français)."""
    return _TRADUCTIONS.get(_langue_active, {}).get(
        cle, _TRADUCTIONS["fr"].get(cle, cle)
    )
